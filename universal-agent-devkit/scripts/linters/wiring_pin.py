#!/usr/bin/env python3
"""
wiring_pin.py — wiring pins when logic is extracted from an Android View (docs/workflow-improvements.md I.3 P4).

REGEX-BASED, not a Kotlin parser: it can miss a View whose header spans lines or builds its supertype through a typealias,
and it reads one directory (the package) as "next to the View". Standard library only.

Why: logic pulled out of a `View` into a new `internal object` gets a unit test of the object, and that test stays green when the
View's call site is reverted (the vacuity gate called such a test empty). The wiring (the View still calls the object, the old
branch is gone) is what a source-text pin proves.

  wiring_pin.py scan [--root DIR] [--base REF]
      For every non-test .kt file changed since REF (default HEAD, untracked files included) that declares a NEW `internal object`
      with a View class in the same directory: PIN NEEDED when no test names that View (print a pin test skeleton: the View still
      names the object, no longer holds the removed lines); UNWIRED when no View names the object at all. Exit 0 nothing to do,
      1 something to do, 2 usage / not a git repo.
  wiring_pin.py verify PIN.kt [--root MODULE_DIR]
      Read back a pin generated by `scan` and evaluate ITS OWN literals against the View source (paths in the pin are relative to
      the module dir, where Gradle runs unit tests: --root defaults to the cwd). Exit 0 holds, 1 broken, 2 a pin verify cannot fully
      read: not a generated pin, a view.contains( it cannot parse as an assertion (fail closed: a formatter-wrapped one is parsed), no
      call assertion or no old-branch assertion, or a File(...) path that leaves --root. A call named only in a comment or KDoc does not
      count; an old-branch line pasted back as a comment does. kotlinc is not needed. The Kotlin skeleton itself is generated text: it is
      read back here, not compiled here.

ponytail: a text pin sees the literal `Object.` and the removed lines, not a call that moved into a branch that never runs; the full
version generates the pin from the diff automatically at Stop (post-fix-gate's vacuity message calls scan and writes the file) and
checks it by revert-and-rerun in the gate. Upgrade when pins keep going stale because the View was refactored again.
"""
import argparse
import os
import re
import subprocess
import sys

OBJ_RX = re.compile(r"^[ \t]*internal[ \t]+object[ \t]+(\w+)", re.M)
CLASS_RX = re.compile(r"\bclass\s+(\w+)")
VIEW_SUPER_RX = re.compile(r"[:,]\s*[\w.]*(?:View|ViewGroup|Layout)\s*\(")   # ViewModel( must not match
PKG_RX = re.compile(r"^package\s+([\w.]+)", re.M)
TEST_PATH_RX = re.compile(r"(^|/)src/(test|androidTest)/|Tests?\.kt$")
FILE_RX = re.compile(r'File\("((?:[^"\\]|\\.)*)"\)')
# one assertion as `scan` writes it, or as ktlint / Spotless re-wraps it (line breaks, a trailing comma)
ASSERT_RX = re.compile(r'assert(True|False)\(\s*"(?:[^"\\]|\\.)*"\s*,\s*view\.contains\(\s*"((?:[^"\\]|\\.)*)"\s*\)\s*,?\s*\)')
CONTAINS_RX = re.compile(r"\bview\.contains\s*\(")
CHAR_RX = re.compile(r"'(?:\\u[0-9a-fA-F]{4}|\\.|[^\\'\n])'")
CUT = "----8<----"
GIT_TIMEOUT_S = 30


def git(root, *args, check=True):
    try:
        p = subprocess.run(["git", "-C", root, *args], capture_output=True, text=True, timeout=GIT_TIMEOUT_S)
    except (OSError, subprocess.TimeoutExpired) as e:
        print(f"wiring_pin: git {' '.join(args[:2])} failed: {e}", file=sys.stderr)
        sys.exit(2)
    if check and p.returncode != 0:
        print(f"wiring_pin: git {' '.join(args[:2])} failed ({p.returncode}): {p.stderr.strip()[:200]}", file=sys.stderr)
        sys.exit(2)
    return p


def read(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except OSError:
        return None


def blank(src, strings=False):
    """`src` with every comment replaced by spaces (newlines kept) and, with strings=True, the inside of every string and char literal too:
    a token search or a count then sees code only. Respects "..." with escapes, raw triple-quoted strings, char literals and nested block
    comments. ponytail: a `${...}` template with a nested string is read as part of the outer string; upgrade if a real View trips it."""
    out, i, n = [], 0, len(src)
    while i < n:
        if src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
        elif src.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if src.startswith("/*", j):
                    depth, j = depth + 1, j + 2
                elif src.startswith("*/", j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            out.append(re.sub(r"[^\n]", " ", src[i:j]))
            i = j
        elif src.startswith('"""', i):
            j = src.find('"""', i + 3)
            j = n if j < 0 else j + 3
            out.append('"""' + re.sub(r"[^\n]", " ", src[i + 3:j - 3]) + '"""' if strings and j - i >= 6 else src[i:j])
            i = j
        elif src[i] == '"':
            j = i + 1
            while j < n and src[j] != '"' and src[j] != "\n":
                j += 2 if src[j] == "\\" else 1
            j = min(j + 1, n)
            out.append('"' + " " * max(j - i - 2, 0) + '"' if strings and j - i >= 2 else src[i:j])
            i = j
        elif src[i] == "'" and CHAR_RX.match(src, i):
            j = CHAR_RX.match(src, i).end()
            out.append("'" + " " * (j - i - 2) + "'" if strings else src[i:j])
            i = j
        else:
            out.append(src[i])
            i += 1
    return "".join(out)


def kt_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


def kt_unescape(s):
    return re.sub(r"\\(.)", r"\1", s)


def view_classes(text):
    out = []
    for m in CLASS_RX.finditer(text):
        head = text[m.end():m.end() + 600].split("{", 1)[0]
        if VIEW_SUPER_RX.search(head):
            out.append(m.group(1))
    return out


def removed_markers(root, base, rel, current):
    """Lines the diff removed from the View, as pin markers: stripped, long enough to mean something, not code that is still there."""
    p = git(root, "diff", "-U0", base, "--", rel, check=False)
    seen, out = set(), []
    for line in p.stdout.splitlines():
        if not line.startswith("-") or line.startswith("---"):
            continue
        s = line[1:].strip()
        if len(s) < 12 or s.startswith(("//", "/*", "*", "import ", "package ")) or re.fullmatch(r"[{}()\[\]\s,;]*", s):
            continue
        if s in current or s in seen:
            continue
        seen.add(s)
        out.append(s)
    return sorted(out, key=len, reverse=True)[:3]


def module_of(root, rel):
    d = os.path.dirname(rel)
    while d:
        if os.path.exists(os.path.join(root, d, "build.gradle.kts")) or os.path.exists(os.path.join(root, d, "build.gradle")):
            return d
        d = os.path.dirname(d)
    return ""


def skeleton(cls, obj, view_rel, view_text, module, markers):
    pkg = PKG_RX.search(view_text)
    rel_in_module = os.path.relpath(view_rel, module) if module else view_rel
    lines = []
    if pkg:
        lines += [f"package {pkg.group(1)}", ""]
    lines += ["import java.io.File", "import org.junit.Assert.assertFalse", "import org.junit.Assert.assertTrue", "import org.junit.Test", "",
              f"/** Wiring pin for {cls} -> {obj} (generated by scripts/linters/wiring_pin.py; `verify` reads it back). */",
              f"class {cls}WiringPinTest {{",
              f'    private val view = File("{kt_escape(rel_in_module)}").readText()', "",
              "    @Test",
              f"    fun viewStillCalls{obj}() {{",
              f'        assertTrue("{cls} must call {obj}", view.contains("{kt_escape(obj + ".")}"))',
              "    }", ""]
    lines += ["    @Test", "    fun viewNoLongerHoldsTheOldBranch() {"]
    if markers:
        for m in markers:
            lines.append(f'        assertFalse("old branch is back in {cls}: {kt_escape(m)}", view.contains("{kt_escape(m)}"))')
    else:
        lines.append(f"        // no removed line qualified as a marker: add one assertFalse(msg, view.contains(\"<code the View no longer holds>\"))")
    lines += ["    }", "}"]
    return "\n".join(lines) + "\n"


def pin_path(view_rel, view_text, module, cls):
    d = os.path.dirname(view_rel)
    dest_dir = re.sub(r"(^|/)src/main/(java|kotlin)(?=/|$)", r"\1src/test/\2", d, count=1)   # mirror the View's package under src/test
    if dest_dir == d:
        pkg = PKG_RX.search(view_text)
        dest_dir = os.path.join(module, "src/test/kotlin", pkg.group(1).replace(".", "/") if pkg else "").rstrip("/")
    return f"{dest_dir}/{cls}WiringPinTest.kt"


def scan(root, base):
    top = git(root, "rev-parse", "--show-toplevel").stdout.strip()
    changed = set(git(top, "diff", "--name-only", base).stdout.split("\n")) | set(git(top, "ls-files", "--others", "--exclude-standard").stdout.split("\n"))
    changed = sorted(f for f in changed if f.endswith(".kt") and not TEST_PATH_RX.search(f))
    all_kt = sorted(set(git(top, "ls-files", "*.kt").stdout.split("\n")) | set(git(top, "ls-files", "--others", "--exclude-standard", "*.kt").stdout.split("\n")))
    tests = [(f, read(os.path.join(top, f)) or "") for f in all_kt if f and TEST_PATH_RX.search(f)]
    found = 0
    for rel in changed:
        cur = read(os.path.join(top, rel))
        if cur is None:
            continue
        old = git(top, "show", f"{base}:{rel}", check=False)
        old_names = set(OBJ_RX.findall(old.stdout)) if old.returncode == 0 else set()
        new_objs = [n for n in OBJ_RX.findall(cur) if n not in old_names]
        if not new_objs:
            continue
        d = os.path.dirname(rel)
        views = {}
        for sib in sorted(os.listdir(os.path.join(top, d)) if os.path.isdir(os.path.join(top, d)) else []):
            srel = os.path.join(d, sib)
            if sib.endswith(".kt") and srel != rel and not TEST_PATH_RX.search(srel):
                stext = read(os.path.join(top, srel)) or ""
                for cls in view_classes(stext):
                    views[cls] = (srel, stext)
        if not views:
            continue
        for obj in new_objs:
            word = re.compile(r"\b%s\b" % re.escape(obj))
            callers = [(c, vr, vt) for c, (vr, vt) in views.items() if word.search(vt)]
            if not callers:
                found += 1
                print(f"wiring-pin: UNWIRED - internal object {obj} ({rel}) sits next to View(s) {', '.join(sorted(views))}, "
                      f"but none of them names it: it is reachable from tests only")
                continue
            obj_tests = [t for t, tt in tests if word.search(tt)]
            for cls, vrel, vtext in callers:
                view_word = re.compile(r"\b%s\b" % re.escape(cls))
                if any(view_word.search(tt) for _t, tt in tests):
                    continue
                found += 1
                module = module_of(top, vrel)
                print(f"wiring-pin: PIN NEEDED - internal object {obj} ({rel}) is called by View {cls} ({vrel}); "
                      f"tests that name {obj}: {', '.join(obj_tests) or 'none'}; tests that name {cls}: none")
                print(f"  save as: {pin_path(vrel, vtext, module, cls)}")
                print(f"  then: wiring_pin.py verify <that file> --root {module or '.'}   (cwd = module dir, as Gradle runs the test)")
                print(CUT)
                sys.stdout.write(skeleton(cls, obj, vrel, vtext, module, removed_markers(top, base, vrel, vtext)))
                print(CUT)
    return 1 if found else 0


def verify(pin, root):
    text = read(pin)
    if text is None:
        print(f"wiring_pin: cannot read {pin}", file=sys.stderr)
        return 2
    code = blank(text)   # what Kotlin would run: comments out, strings kept
    f = FILE_RX.search(code)
    asserts = ASSERT_RX.findall(code)
    if not f or not asserts:
        print(f"wiring_pin: {pin} is not a wiring pin generated by `scan` (no File(...) path or no view.contains assertion)", file=sys.stderr)
        return 2
    calls = len(CONTAINS_RX.findall(blank(text, strings=True)))
    if calls != len(asserts):   # fail closed: an assertion verify cannot read would otherwise be silently skipped
        print(f"wiring_pin: {pin} has {calls} view.contains( call(s) in code but only {len(asserts)} assertion(s) of the form "
              f"assertTrue|assertFalse(\"msg\", view.contains(\"literal\")) that verify can read: put the rest in that form or check it by hand",
              file=sys.stderr)
        return 2
    if not {k for k, _t in asserts} >= {"True", "False"}:
        print(f"wiring_pin: {pin} lacks a call assertion or an old-branch assertion: a pin without both proves nothing about the wiring "
              f"(when no removed line qualifies as a marker, write the old-branch assertion by hand)", file=sys.stderr)
        return 2
    real_root = os.path.realpath(root)
    vpath = os.path.join(root, kt_unescape(f.group(1)))
    if os.path.commonpath([real_root, os.path.realpath(vpath)]) != real_root:
        print(f"wiring_pin: {pin} names a View path outside --root ({vpath}): refused", file=sys.stderr)
        return 2
    view = read(vpath)
    if view is None:
        print(f"BROKEN: the View file {vpath} is gone: moved or deleted, so the pin cannot hold")
        return 1
    view_code = blank(view)   # a call named only in a comment or KDoc is not a call; the old-branch check keeps the raw text
    broken = 0
    for kind, tok in asserts:
        tok = kt_unescape(tok)
        if kind == "True" and tok not in view_code:
            broken += 1
            print(f"BROKEN: the View no longer calls {tok!r}: the call site was reverted or the object is unwired")
        if kind == "False" and tok in view:
            broken += 1
            print(f"BROKEN: old branch is back in the View: {tok!r}")
    if not broken:
        print(f"wiring pin holds: {len(asserts)} assertion(s) on {vpath}")
    return 1 if broken else 0


def main(argv):
    ap = argparse.ArgumentParser(prog="wiring_pin.py", description=__doc__.split("\n")[1])
    sub = ap.add_subparsers(dest="cmd")
    s = sub.add_parser("scan")
    s.add_argument("--root", default=".")
    s.add_argument("--base", default="HEAD")
    v = sub.add_parser("verify")
    v.add_argument("pin")
    v.add_argument("--root", default=".")
    try:
        a = ap.parse_args(argv)
    except SystemExit as e:
        return 2 if e.code not in (0, None) else 0
    if a.cmd == "scan":
        return scan(os.path.abspath(a.root), a.base)
    if a.cmd == "verify":
        return verify(a.pin, os.path.abspath(a.root))
    ap.print_usage(sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
