#!/usr/bin/env bash
# 10/11/2026 (GeelyEx2, PR #328): merge gate verify trong worktree scratch không có tools/landing-page/node_modules (git ignore), nên
# REG-WEB-01 (tsc --noEmit của landing) luôn exit 2 = UNTESTED và mọi PR chạm landing không merge được. Luật:
#   1. package.json + lockfile của thư mục đó giống hệt main ⇒ super-board-scratch-config.sh clone (APFS) node_modules thật của main
#      sang scratch, symlink bên trong (pnpm) giữ nguyên dạng link, và `git status` của scratch vẫn sạch;
#   2. package.json hoặc lockfile khác main (PR đổi dependency) ⇒ KHÔNG chép: kiểm bằng module cũ của main là xanh giả, exit 2 đúng hơn;
#   3. node_modules của main là symlink ⇒ không chép (link mượn node_modules không phải việc, worktree.py A.4).
# Chỉ macOS (clonefile). Tương thích bash 3.2.
set -u
export LC_ALL=C LANG=C
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SCRIPT="$ROOT/.claude/bin/super-board-scratch-config.sh"
for _dk in "$ROOT/universal-agent-devkit" "$ROOT/.agents/devkit"; do
  if [ -f "$_dk/tests/lib/clean_git_env.sh" ]; then . "$_dk/tests/lib/clean_git_env.sh"; break; fi
done
if [ "$(uname)" != Darwin ]; then echo "SKIP: cần macOS (clonefile)"; exit 0; fi
FAILS=0
ok() { echo "✔ $1"; }
fail() { echo "✖ $1"; FAILS=$((FAILS + 1)); }

TMP="$(mktemp -d "${TMPDIR:-/tmp}/sb-scratchnm-test.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT
R="$TMP/repo"; S="$R/.claude/worktrees/.merge-scratch-x"
git init -q -b main "$R"
git -C "$R" config user.email t@example.invalid; git -C "$R" config user.name t
printf '/.claude/worktrees/\n' > "$R/.gitignore"
for d in same diff linked; do
  mkdir -p "$R/$d"
  printf 'node_modules/\n' > "$R/$d/.gitignore"   # như tools/landing-page/.gitignore: có dấu / cuối
  printf '{"name":"%s"}\n' "$d" > "$R/$d/package.json"
  printf 'lockfileVersion: 9\n' > "$R/$d/pnpm-lock.yaml"
done
git -C "$R" add -A; git -C "$R" commit -qm init
# PR đổi lockfile của diff/
git -C "$R" branch -q pr main
git -C "$R" worktree add -q "$TMP/prwt" pr
printf 'lockfileVersion: 9\nnew: dep\n' > "$TMP/prwt/diff/pnpm-lock.yaml"
git -C "$TMP/prwt" commit -qam bump
git -C "$R" worktree remove --force "$TMP/prwt"
git -C "$R" worktree add -q --detach "$S" pr

# node_modules thật của main (bị ignore), kiểu pnpm: thư mục thật + symlink tương đối vào .pnpm
for d in same diff; do
  mkdir -p "$R/$d/node_modules/.pnpm/ts@5/node_modules/ts/bin" "$R/$d/node_modules/.bin"
  echo 'console.log(1)' > "$R/$d/node_modules/.pnpm/ts@5/node_modules/ts/bin/tsc"
  ln -s .pnpm/ts@5/node_modules/ts "$R/$d/node_modules/ts"
  ln -s ../ts/bin/tsc "$R/$d/node_modules/.bin/tsc"
done
mkdir -p "$TMP/elsewhere/nm/ts"; echo x > "$TMP/elsewhere/nm/ts/a"
ln -s "$TMP/elsewhere/nm" "$R/linked/node_modules"

bash "$SCRIPT" "$R" "$S" > "$TMP/out.log" 2>&1

if [ -f "$S/same/node_modules/.bin/tsc" ] && [ ! -L "$S/same/node_modules" ] && [ -L "$S/same/node_modules/ts" ] \
   && [ "$(cat "$S/same/node_modules/.bin/tsc")" = 'console.log(1)' ]; then
  ok "lockfile giống main: node_modules được clone, symlink pnpm bên trong giữ dạng link"
else
  fail "lockfile giống main: không thấy node_modules clone đúng trong scratch ($(tail -3 "$TMP/out.log" | tr '\n' ' '))"
fi
if [ ! -e "$S/diff/node_modules" ] && [ ! -L "$S/diff/node_modules" ]; then
  ok "lockfile khác main: không chép (REG-WEB-01 vẫn exit 2 thật)"
else
  fail "lockfile khác main: đã chép node_modules cũ của main — xanh giả"
fi
if [ ! -e "$S/linked/node_modules" ] && [ ! -L "$S/linked/node_modules" ]; then
  ok "node_modules của main là symlink: không chép"
else
  fail "node_modules của main là symlink: đã chép/link sang scratch"
fi
st=$(git -C "$S" status --porcelain)
if [ -z "$st" ]; then ok "git status của scratch sạch sau khi chép"; else fail "scratch có thay đổi git thấy: $st"; fi
# Chạy lại không làm hỏng bản đã có (đích đã tồn tại thì để yên)
echo keep > "$S/same/node_modules/marker"
bash "$SCRIPT" "$R" "$S" > "$TMP/out2.log" 2>&1
if [ -f "$S/same/node_modules/marker" ]; then ok "chạy lại: node_modules đã có trong scratch được để yên"; else fail "chạy lại: node_modules của scratch bị thay"; fi

[ "$FAILS" -eq 0 ] && echo "PASS: test_scratch_config_node_modules" || echo "FAIL: $FAILS"
exit "$FAILS"
